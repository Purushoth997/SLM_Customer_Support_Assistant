def save_raw_dataset(output_path: str = str(PROJECT_ROOT / "data" / "raw" / "customer_support_dataset.json")) -> Path:
    """Generate and save the raw dataset."""
    dest = Path(output_path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dataset = build_raw_dataset(seed=42)
    with open(dest, "w", encoding="utf-8") as f:
        json.dump(dataset, f, indent=2, ensure_ascii=False)
    logger.info("Raw dataset saved to: %s", dest)
    return dest


